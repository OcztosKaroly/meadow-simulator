using UnityEngine;

/// <summary>
/// Defines every types of scenes in the application.
/// </summary>
public enum ESceneType
{
    /// <summary>
    /// The main menu scene where users can start the simulation or access settings.
    /// </summary>
    MainMenu,

    /// <summary>
    /// The settings scene where users can configure application preferences.
    /// </summary>
    Settings,
    
    /// <summary>
    /// The simulation scene where the main gameplay takes place.
    /// </summary>
    Simulation
}
